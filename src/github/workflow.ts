import type { Config } from '../config/schema.js';

export const WORKFLOW_PATH = '.github/workflows/vcs-protection-guard.yml';

const yq = (s: string) => `'${s.replace(/'/g, "''")}'`;

/**
 * GitHub Actions workflow that acts as the server-side guard when GitHub branch protection
 * is not available. `pinnedVersion` should be the published package version.
 */
/** The concurrency group expression (see the comment in the generated workflow). */
export const CONCURRENCY_KEY =
  "(github.event_name == 'workflow_run' && format('pill-{0}', github.run_id))" +
  " || ((github.event_name == 'schedule' || github.event_name == 'workflow_dispatch') && 'sweep')" +
  " || (github.event.pull_request.number && format('pr-{0}', github.event.pull_request.number))" +
  " || (github.event_name == 'delete' && format('branch-{0}', github.event.ref))" +
  " || format('branch-{0}', github.ref_name)";

export function renderWorkflow(config: Config, pinnedVersion: string): string {
  const branches = config.protected.map((r) => `      - ${yq(r.pattern)}`).join('\n');
  const pill = config.github.poisonPill;
  const poison = pill.enabled && pill.workflows.length > 0;
  // Wakes the guard when a critical workflow finishes (poison pill). GitHub runs workflow_run
  // workflows from the default branch, so a pushed commit can't edit this check away.
  const workflowRun = poison
    ? `
  workflow_run:
    workflows: [${pill.workflows.map(yq).join(', ')}]
    types: [completed]
    branches:
${branches}`
    : '';
  // The sweep re-checks every protected branch on a schedule: it catches pushes that started no
  // workflow ("[skip ci]") and runs GitHub cancelled in the concurrency queue.
  const sweep = config.github.sweep ? `\n  schedule:\n    - cron: ${yq(config.github.sweep)}` : '';
  const extraPermissions = poison ? '\n  checks: read\n  actions: read' : '';
  return `# Generated by vcs-protection. Regenerate with: vcs-protection github setup
# Server-side guard for protected branches. It reverts (or reports) commits on protected branches
# that did not come from a pull request with the required approvals.
name: vcs-protection guard

on:
  push:
    branches:
${branches}
  delete:
  pull_request:
    types: [opened, synchronize, reopened, edited]
  pull_request_review:
    types: [submitted, edited, dismissed]${workflowRun}${sweep}
  workflow_dispatch:
    inputs:
      baseline:
        description: 'Mark the current tip of every protected branch as verified (first setup, or after an upgrade)'
        type: boolean
        default: false

permissions:
  contents: write
  issues: write
  pull-requests: read
  statuses: write${extraPermissions}

# One queue per branch for pushes and deletions; the sweep has its own; every poison-pill run is
# independent (a queued one is never cancelled); pull requests queue per PR.
concurrency:
  group: vcs-protection-\${{ ${CONCURRENCY_KEY} }}
  cancel-in-progress: false

jobs:
  guard:
    runs-on: ubuntu-latest
    timeout-minutes: 5
    steps:
      - uses: actions/setup-node@v4
        with:
          node-version: 22
      - name: vcs-protection guard
        run: npx --yes vcs-protection@${pinnedVersion} ci-guard
        env:
          GITHUB_TOKEN: \${{ secrets.GITHUB_TOKEN }}
          VCS_PROTECTION_GUARD_LOGIN: ${yq(config.github.guardLogin)}
`;
}
